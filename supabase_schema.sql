-- 1. Enable required extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Create Public Profiles Table (Linked to auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT,
    full_name TEXT,
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Habits Table (Scoped to user_id)
CREATE TABLE IF NOT EXISTS public.habits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    emoji TEXT NOT NULL DEFAULT '🎯',
    color TEXT NOT NULL DEFAULT '#38bdf8',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Create Habit Logs Table (Scoped to habit_id & user_id)
CREATE TABLE IF NOT EXISTS public.habit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id BIGINT NOT NULL REFERENCES public.habits(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    date DATE NOT NULL,
    done BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_habit_date UNIQUE (habit_id, date)
);

-- 5. Indexes for fast query performance
CREATE INDEX IF NOT EXISTS idx_habits_user_id ON public.habits(user_id);
CREATE INDEX IF NOT EXISTS idx_habit_logs_user_id ON public.habit_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_habit_logs_habit_id_date ON public.habit_logs(habit_id, date);

-- 6. Enable Row Level Security (RLS) on all tables
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.habits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.habit_logs ENABLE ROW LEVEL SECURITY;

-- 7. Row Level Security Policies (Users can ONLY view and edit their own data)

-- Profiles Policies
DROP POLICY IF EXISTS "Users can view own profile" ON public.profiles;
CREATE POLICY "Users can view own profile" 
    ON public.profiles FOR SELECT 
    USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update own profile" ON public.profiles;
CREATE POLICY "Users can update own profile" 
    ON public.profiles FOR UPDATE 
    USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can insert own profile" ON public.profiles;
CREATE POLICY "Users can insert own profile" 
    ON public.profiles FOR INSERT 
    WITH CHECK (auth.uid() = id);

-- Habits Policies
DROP POLICY IF EXISTS "Users can view own habits" ON public.habits;
CREATE POLICY "Users can view own habits" 
    ON public.habits FOR SELECT 
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert own habits" ON public.habits;
CREATE POLICY "Users can insert own habits" 
    ON public.habits FOR INSERT 
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update own habits" ON public.habits;
CREATE POLICY "Users can update own habits" 
    ON public.habits FOR UPDATE 
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete own habits" ON public.habits;
CREATE POLICY "Users can delete own habits" 
    ON public.habits FOR DELETE 
    USING (auth.uid() = user_id);

-- Habit Logs Policies
DROP POLICY IF EXISTS "Users can view own logs" ON public.habit_logs;
CREATE POLICY "Users can view own logs" 
    ON public.habit_logs FOR SELECT 
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert own logs" ON public.habit_logs;
CREATE POLICY "Users can insert own logs" 
    ON public.habit_logs FOR INSERT 
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update own logs" ON public.habit_logs;
CREATE POLICY "Users can update own logs" 
    ON public.habit_logs FOR UPDATE 
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete own logs" ON public.habit_logs;
CREATE POLICY "Users can delete own logs" 
    ON public.habit_logs FOR DELETE 
    USING (auth.uid() = user_id);


-- 8. Function & Trigger: Automatic User Onboarding & Personalized Dataset Seeding
-- When a user registers, this automatically creates their profile and generates
-- a realistic 90-day behavior analysis dataset across 4 habits for them!
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    new_user_id UUID;
    h1_id BIGINT;
    h2_id BIGINT;
    h3_id BIGINT;
    h4_id BIGINT;
    i INT;
    log_d DATE;
    p FLOAT;
    is_done BOOLEAN;
BEGIN
    new_user_id := NEW.id;

    -- A. Insert profile
    INSERT INTO public.profiles (id, email, full_name, avatar_url)
    VALUES (
        new_user_id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'full_name', split_part(NEW.email, '@', 1)),
        COALESCE(NEW.raw_user_meta_data->>'avatar_url', '')
    );

    -- B. Seed Habit 1: Morning Run
    INSERT INTO public.habits (user_id, name, emoji, color)
    VALUES (new_user_id, 'Morning Run', '🏃', '#f97316')
    RETURNING id INTO h1_id;

    -- Seed Habit 2: Read 30 min
    INSERT INTO public.habits (user_id, name, emoji, color)
    VALUES (new_user_id, 'Read 30 min', '📚', '#38bdf8')
    RETURNING id INTO h2_id;

    -- Seed Habit 3: Meditate
    INSERT INTO public.habits (user_id, name, emoji, color)
    VALUES (new_user_id, 'Meditate', '🧘', '#a78bfa')
    RETURNING id INTO h3_id;

    -- Seed Habit 4: Cold Shower
    INSERT INTO public.habits (user_id, name, emoji, color)
    VALUES (new_user_id, 'Cold Shower', '🚿', '#34d399')
    RETURNING id INTO h4_id;

    -- C. Generate 90 days of realistic behavioral history for this new user
    FOR i IN 0..89 LOOP
        log_d := CURRENT_DATE - (89 - i);

        -- Habit 1: Dropper profile (strong at first, drops off)
        p := CASE WHEN i < 40 THEN 0.80 WHEN i < 60 THEN 0.25 ELSE 0.65 END;
        is_done := (random() < p);
        INSERT INTO public.habit_logs (habit_id, user_id, date, done)
        VALUES (h1_id, new_user_id, log_d, is_done);

        -- Habit 2: Riser profile (gradually building momentum)
        p := CASE WHEN i < 30 THEN 0.35 WHEN i < 60 THEN 0.65 ELSE 0.88 END;
        is_done := (random() < p);
        INSERT INTO public.habit_logs (habit_id, user_id, date, done)
        VALUES (h2_id, new_user_id, log_d, is_done);

        -- Habit 3: Weekend warrior profile (high on weekends)
        p := CASE WHEN EXTRACT(ISODOW FROM log_d) IN (6, 7) THEN 0.90 ELSE 0.30 END;
        is_done := (random() < p);
        INSERT INTO public.habit_logs (habit_id, user_id, date, done)
        VALUES (h3_id, new_user_id, log_d, is_done);

        -- Habit 4: Steady baseline
        p := 0.68;
        is_done := (random() < p);
        INSERT INTO public.habit_logs (habit_id, user_id, date, done)
        VALUES (h4_id, new_user_id, log_d, is_done);
    END LOOP;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 9. Attach the trigger to auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

